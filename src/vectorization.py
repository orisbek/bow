from sklearn.feature_extraction.text import CountVectorizer, TfidfVectorizer


def преобразовать_обучение_тест(тексты_обучения, тексты_теста):
    """Создает и трансформирует векторизацию для обучения и тестирования.
    
    Args:
        тексты_обучения: Тексты для обучения
        тексты_теста: Тексты для тестирования
        
    Returns:
        Словарь с BOW и TF-IDF векторами
    """
    # Инициализируем векторизаторы
    мешок_слов = CountVectorizer(ngram_range=(1, 1), min_df=1, lowercase=True, token_pattern=r'[а-яёА-ЯЁ]+')
    тф_идф = TfidfVectorizer(ngram_range=(1, 1), min_df=1, lowercase=True, token_pattern=r'[а-яёА-ЯЁ]+')
    
    # Обучаем на переданных текстах
    X_мешок_обучение = мешок_слов.fit_transform(тексты_обучения)
    X_мешок_тест = мешок_слов.transform(тексты_теста)
    X_тф_идф_обучение = тф_идф.fit_transform(тексты_обучения)
    X_тф_идф_тест = тф_идф.transform(тексты_теста)
    
    return {
        'мешок_слов': (мешок_слов, X_мешок_обучение, X_мешок_тест),
        'тф_идф': (тф_идф, X_тф_идф_обучение, X_тф_идф_тест),
    }
